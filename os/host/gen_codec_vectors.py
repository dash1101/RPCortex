def cstr(s):
    out = ['"']
    for ch in s:
        if ch == "\n": out.append("\\n")
        elif ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\t": out.append("\\t")
        elif ord(ch) < 32 or ord(ch) > 126: out.append("\\%03o" % ord(ch))
        else: out.append(ch)
    out.append('"')
    # Split long literals so no compiler's limit is near.
    text = "".join(out)
    return text


def carr(name, values):
    if not values:
        return "static const uint32_t %s[1] = { 0 };\n" % name
    return "static const uint32_t %s[] = { %s };\n" % (name, ", ".join(str(int(v)) for v in values))


