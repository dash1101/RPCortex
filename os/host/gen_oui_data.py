#!/usr/bin/env python3
"""Generate novaoui_data.inc: the MAC-prefix vendor table, as binary data.

    gen_oui_data.py [--novad1 DIR] [--tests DIR] [-o ../apps/novad1/novaoui_data.inc]

The table itself came from the IEEE MA-L registry through the MicroPython suite's own
generator (tools/novad1/genoui.py), and lives in novaoui.py as one sorted string of
8-character records. This reads that module and rewrites the records as bytes: three
for the prefix, one for the vendor, so 1013 of them are 4 KB in the flash slot instead
of 8 KB of text. Nothing here is typed in. A prefix that is not in the table is not a
vendor; the lookup returns nothing for it rather than a guess.
"""
import argparse
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--novad1", default=os.path.join(here, "..", "..", "..", "RPCortex-repo", "repo", "packages", "novad1"))
ap.add_argument("--tests", default=os.path.join(here, "..", "..", "..", "RPCortex-repo", "repo", "tests", "novad1"))
ap.add_argument("-o", "--out", default=os.path.join(here, "..", "apps", "novad1", "novaoui_data.inc"))
args = ap.parse_args()

sys.path.insert(0, os.path.abspath(args.tests))
import _shims  # noqa: E402
_shims.install()
sys.path.insert(0, os.path.abspath(args.novad1))
import novaoui  # noqa: E402

T = novaoui._T
assert len(T) % 8 == 0
recs = [(int(T[i:i + 6], 16), int(T[i + 6:i + 8], 16)) for i in range(0, len(T), 8)]
assert recs == sorted(recs), "the table must be sorted for the binary search"
assert len(novaoui.VENDORS) == len(novaoui.CLASSES) < 256

classes = []
for c in novaoui.CLASSES:
    if c not in classes:
        classes.append(c)


def cblob(words):
    return '"' + "".join(w + "\\0" for w in words) + '"'


out = []
w = out.append
w("// GENERATED by os/host/gen_oui_data.py from the MicroPython suite's novaoui.py, which\n")
w("// took it from the IEEE MA-L registry. Do not edit; regenerate.\n")
w("//\n// %d prefixes, %d vendors. Pointer-free on purpose: an array of strings would be\n" % (len(recs), len(novaoui.VENDORS)))
w("// relocated into RAM in a PIC package, and these are flash.\n\n")
w("static const char kOuiVendors[] = %s;\n" % cblob(novaoui.VENDORS))
w("static const char kOuiClassNames[] = %s;\n" % cblob(classes))
w("static const uint8_t kOuiVendorClass[] = { %s };\n" % ", ".join(str(classes.index(c)) for c in novaoui.CLASSES))
w("#define OUI_VENDORS_N %d\n#define OUI_CLASSES_N %d\n#define OUI_N %d\n" % (len(novaoui.VENDORS), len(classes), len(recs)))
w("static const uint8_t kOuiTable[] = {\n")
for i in range(0, len(recs), 6):
    w("    " + ", ".join("0x%02X, 0x%02X, 0x%02X, %d" % ((p >> 16) & 255, (p >> 8) & 255, p & 255, v) for p, v in recs[i:i + 6]) + ",\n")
w("};\n")
with open(args.out, "w") as f:
    f.write("".join(out))
print("wrote %s: %d prefixes, %d vendors, %d classes" % (args.out, len(recs), len(novaoui.VENDORS), len(classes)))
