void fb_pixel(FrameBuf *f, int x, int y, int colour) {
    if (!f || !f->buf) return;
    if (x < 0 || y < 0 || x >= f->w || y >= f->h) return;   // clipped, not wrapped
    uint8_t *p = &f->buf[(y >> 3) * f->w + x];
    uint8_t  m = (uint8_t)(1u << (y & 7));
    if (colour) *p |= m; else *p &= (uint8_t)~m;
}

int fb_get(const FrameBuf *f, int x, int y) {
    if (!f || !f->buf) return 0;
    if (x < 0 || y < 0 || x >= f->w || y >= f->h) return 0;
    return (f->buf[(y >> 3) * f->w + x] >> (y & 7)) & 1;
}

void fb_fill(FrameBuf *f, int colour) {
    if (!f || !f->buf) return;
    memset(f->buf, colour ? 0xff : 0x00, (size_t)fb_bytes(f->w, f->h));
}

void fb_hline(FrameBuf *f, int x, int y, int len, int colour) {
    for (int i = 0; i < len; i++) fb_pixel(f, x + i, y, colour);
}

void fb_vline(FrameBuf *f, int x, int y, int len, int colour) {
    for (int i = 0; i < len; i++) fb_pixel(f, x, y + i, colour);
}

// Bresenham, so a diagonal is drawn with integer arithmetic only — there is no
// FPU on either chip and a float here would be both slower and heavier.
void fb_line(FrameBuf *f, int x0, int y0, int x1, int y1, int colour) {
    int dx = x1 - x0, dy = y1 - y0;
    int sx = dx < 0 ? -1 : 1, sy = dy < 0 ? -1 : 1;
    if (dx < 0) dx = -dx;
    if (dy < 0) dy = -dy;
    int err = dx - dy;
    while (true) {
        fb_pixel(f, x0, y0, colour);
        if (x0 == x1 && y0 == y1) break;
        int e2 = err * 2;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 <  dx) { err += dx; y0 += sy; }
    }
}

void fb_rect(FrameBuf *f, int x, int y, int w, int h, int colour, int filled) {
    if (w <= 0 || h <= 0) return;
    if (filled) {
        for (int i = 0; i < h; i++) fb_hline(f, x, y + i, w, colour);
        return;
    }
    fb_hline(f, x, y, w, colour);
    fb_hline(f, x, y + h - 1, w, colour);
    fb_vline(f, x, y, h, colour);
    fb_vline(f, x + w - 1, y, h, colour);
}

int fb_text_width(const char *s) {
    if (!s) return 0;
    int n = 0;
    while (*s++) n++;
    // The trailing gap is not part of the text, so a right-aligned string sits
    // where it looks like it should.
    return n ? n * FONT_ADVANCE - 1 : 0;
}

void fb_text(FrameBuf *f, const char *s, int x, int y, int colour) {
    if (!f || !s) return;
    for (; *s; s++, x += FONT_ADVANCE) {
        unsigned char c = (unsigned char)*s;
        if (c < FONT_FIRST || c > FONT_LAST) c = '?';
        const uint8_t *g = &kFont[(c - FONT_FIRST) * FONT_WIDTH];
        for (int col = 0; col < FONT_WIDTH; col++)
            for (int row = 0; row < 7; row++)
                if (g[col] & (1u << row)) fb_pixel(f, x + col, y + row, colour);
    }
}

// Copy `src` into `dst` at (x, y). `transparent` names a colour to skip, or -1
// to copy every pixel — which is the difference between stamping an icon over a
// background and punching a rectangle through it.
void fb_blit(FrameBuf *dst, const FrameBuf *src, int x, int y, int transparent) {
    if (!dst || !src) return;
    for (int sy = 0; sy < src->h; sy++) {
        for (int sx = 0; sx < src->w; sx++) {
            int c = fb_get(src, sx, sy);
            if (c == transparent) continue;
            fb_pixel(dst, x + sx, y + sy, c);
        }
    }
}

// Shift the contents. Vacated pixels are cleared rather than wrapped: a list
// scrolling up wants blank space arriving at the bottom, not the top row
// reappearing there.
void fb_scroll(FrameBuf *f, int dx, int dy) {
    if (!f || !f->buf || (dx == 0 && dy == 0)) return;

    // Walk in whichever direction stops a moved pixel overwriting one not yet
    // read. Copying up-left means going forwards; down-right means backwards.
    int x_start = dx > 0 ? f->w - 1 : 0, x_step = dx > 0 ? -1 : 1;
    int y_start = dy > 0 ? f->h - 1 : 0, y_step = dy > 0 ? -1 : 1;

    for (int i = 0; i < f->h; i++) {
        int y = y_start + i * y_step;
        for (int j = 0; j < f->w; j++) {
            int x = x_start + j * x_step;
            int sx = x - dx, sy = y - dy;
            int c = (sx >= 0 && sy >= 0 && sx < f->w && sy < f->h) ? fb_get(f, sx, sy) : 0;
            fb_pixel(f, x, y, c);
        }
    }
}
