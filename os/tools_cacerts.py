#!/usr/bin/env python3
"""The trusted roots, as a table the board searches by subject.

    tools_cacerts.py <roots .pem> <out .cpp>

Each root goes into flash as DER, with where its subject Name sits in it. When a
TLS handshake needs the issuer of a certificate, the board compares the issuer's
DER with these subjects and parses only the root that matches, straight from
flash (httptransport.cpp, ca_lookup). The list can grow without the board
holding every root in RAM, which it did when they were parsed up front.
"""
import base64
import re
import sys


def tlv(buf, at):
    """(tag, header length, content length) of the DER element at `at`."""
    tag = buf[at]
    n = buf[at + 1]
    if n < 0x80:
        return tag, 2, n
    k = n & 0x7F
    if k == 0 or k > 3:
        raise ValueError("unsupported DER length at %d" % at)
    return tag, 2 + k, int.from_bytes(buf[at + 2:at + 2 + k], "big")


def subject_span(der):
    """Offset and length of the subject Name (whole SEQUENCE, tag included)."""
    tag, h, _ = tlv(der, 0)                    # Certificate
    assert tag == 0x30
    at = h
    tag, h, _ = tlv(der, at)                   # tbsCertificate
    assert tag == 0x30
    at += h
    fields = []
    for _ in range(7):                         # [version] serial sigAlg issuer validity subject
        tag, h, n = tlv(der, at)
        fields.append((tag, at, h + n))
        at += h + n
    if fields[0][0] == 0xA0:                   # explicit version present
        fields = fields[1:]
    tag, off, length = fields[4]               # serial, sigAlg, issuer, validity, SUBJECT
    assert tag == 0x30, "subject is not a SEQUENCE"
    # A root signs itself: its issuer is its subject, byte for byte. If the walk
    # above landed anywhere else, the two differ and the build stops here.
    _, ioff, ilen = fields[2]
    if der[ioff:ioff + ilen] != der[off:off + length]:
        raise ValueError("issuer and subject differ: not a self-signed root, or the DER walk is wrong")
    return off, length


def main():
    src, out = sys.argv[1], sys.argv[2]
    pem = open(src).read()
    ders = [base64.b64decode("".join(b.split()))
            for b in re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", pem, re.S)]
    if not ders:
        sys.exit("no certificates in " + src)
    blob = bytearray()
    rows = []
    for d in ders:
        so, sl = subject_span(d)
        rows.append((len(blob), len(d), so, sl))
        blob += d
    with open(out, "w") as f:
        f.write("// Generated by tools_cacerts.py from ca_certs.pem. Do not edit.\n")
        f.write("#include <stdint.h>\n#include \"stockca.h\"\n\n")
        f.write("static const uint8_t k_der[%d] = {\n" % len(blob))
        for i in range(0, len(blob), 16):
            f.write("    " + ", ".join("0x%02x" % b for b in blob[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("const StockCa stock_ca[] = {\n")
        for off, n, so, sl in rows:
            f.write("    { k_der + %d, %d, %d, %d },\n" % (off, n, so, sl))
        f.write("};\n")
        f.write("const unsigned stock_ca_count = %d;\n" % len(rows))
    print("%s: %d roots, %d bytes" % (out, len(rows), len(blob)))


if __name__ == "__main__":
    main()
